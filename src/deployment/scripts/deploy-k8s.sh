#!/usr/bin/env bash
# Deploy the workloads in k8s/ onto the deploy_k8s cluster, with the images deploy_images pushed.
# Everything specific to your project goes in a generated overlay, so k8s/ stays plain YAML.
#   ./scripts/deploy-k8s.sh                  (STACK=dev by default)
set -euo pipefail
cd "$(dirname -- "${BASH_SOURCE[0]}")/.."
stack="${STACK:-dev}"
project="${GOOGLE_CLOUD_PROJECT:?set it in .env}"
bucket="${GREENPATH_BUCKET:?set it in .env}"
output() { (cd "$1" && pulumi stack output --stack "${stack}" "$2"); }

# The cluster, from its stack; always this context, never whatever kubectl last pointed at
cluster="$(output deploy_k8s cluster_name)"
zone="$(output deploy_k8s cluster_location)"
gcloud container clusters get-credentials "${cluster}" --zone "${zone}" --project "${project}"
context="gke_${project}_${zone}_${cluster}"

# image <name in k8s/> <ref from deploy_images>: name:tag@digest -> a kustomize images entry
image() {
    local ref="$2" name
    name="${ref%@*}"
    printf '  - name: %s\n    newName: %s\n    newTag: "%s"\n    digest: %s\n' \
        "$1" "${name%:*}" "${name##*:}" "${ref#*@}"
}

# identity <Kubernetes ServiceAccount> <Google service account>: the Workload Identity annotation, which
# lets the pods act as the Google account (deploy_k8s already allows it)
identity() {
    printf '  - target: { kind: ServiceAccount, name: %s }\n    patch: |\n      - op: add\n        path: /metadata/annotations\n        value:\n          iam.gke.io/gcp-service-account: %s@%s.iam.gserviceaccount.com\n' \
        "$1" "$2" "${project}"
}

overlay=".local/k8s-${stack}"
mkdir -p "${overlay}"
{
    echo "# Generated by scripts/deploy-k8s.sh: k8s/ with this project's settings. Do not edit."
    echo "resources: [../../k8s/gke]"
    echo "images:"
    image greenpath-frontend "$(output deploy_images frontend_ref)"
    image greenpath-api-service "$(output deploy_images api_service_ref)"
    image greenpath-model-service "$(output deploy_images model_service_ref)"
    image greenpath-rag-service "$(output deploy_images rag_service_ref)"
    image greenpath-rag-chroma "$(output deploy_images rag_chroma_ref)"
    cat <<YAML
configMapGenerator:
  - name: api-config
    behavior: merge
    literals: [GCP_PROJECT=${project}, GREENPATH_BUCKET=${bucket}]
  - name: model-config
    behavior: merge
    literals: [GREENPATH_BUCKET=${bucket}]
  - name: rag-config
    behavior: merge
    literals: [GCP_PROJECT=${project}]
generatorOptions:
  disableNameSuffixHash: true
patches:
YAML
    identity api-service greenpath-api-service
    identity model-service greenpath-model-service
    identity rag-service greenpath-rag-service
    identity vector-db greenpath-rag-service
} > "${overlay}/kustomization.yaml"

kubectl --context "${context}" apply -k "${overlay}"

# Wait for every workload, Chroma first (RAG needs it), then for the Gateway's load balancer
for deployment in vector-db rag-service model-service api-service frontend; do
    kubectl --context "${context}" -n greenpath rollout status "deployment/${deployment}" --timeout=600s
done
kubectl --context "${context}" -n greenpath wait gateway/greenpath --for=condition=Programmed --timeout=600s

cat <<MSG

Deployed to ${context}. The load balancer can take a few minutes more before it answers:
  App:    http://$(output deploy_base gateway_ip)
  Watch:  kubectl -n greenpath get pods -o wide
MSG
